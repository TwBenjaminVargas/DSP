#define DELAY 50
#define GAIN 1.8f
#define LEVEL 0.5f

typedef enum {
    MODO_PASO_DIRECTO = 1, // Ejercicio 1 (Paso directo)
    MODO_GANANCIA,         // Ejercicio 2
    MODO_RETARDO,          // Ejercicio 3
    MODO_DESPLAZAMIENTO,    // Ejercicio 4
    MODO_SENAL_SINUSOIDAL, // Ejercicio 5 (Generación Sinusoidal 440 Hz)
    MODO_SENAL_ALEATORIA   // Ejercicio 6 (Generación Señal Aleatoria)
} modo_ejercicio_t;

modo_ejercicio_t seleccionar_ejercicio(void) {
    printf("\n===========================================\n");
    printf("   TP3: Procesamiento de Senales (ESP-IDF)  \n");
    printf("===========================================\n");
    printf(" Seleccione el modo a ejecutar (1-6):\n");
    printf("  1. Paso directo (Ejercicio 1)\n");
    printf("  2. Ganancia (Ejercicio 2)\n");
    printf("  3. Retardo (Ejercicio 3)\n");
    printf("  4. Desplazamiento (Ejercicio 4)\n");
    printf("  5. Senal Sinusoidal local 200 Hz (Ejercicio 5)\n");
    printf("  6. Senal Aleatoria (Ejercicio 6)\n");
    printf("-------------------------------------------\n");
    printf("Ingrese opcion [1-6]: ");
    fflush(stdout);

    int opcion = 0;
    while (opcion < '1' || opcion > '6') {
        opcion = getchar();
        vTaskDelay(pdMS_TO_TICKS(10));
    }

    printf("%c\n\nIniciando Modo %c...\n", opcion, opcion);
    return (modo_ejercicio_t)(opcion - '0');
}

void app_main(void) {
    // 1. Configuración del ADC (GPIO34)
    adc_oneshot_unit_handle_t adc_handle;
    adc_oneshot_unit_init_cfg_t init_config = { .unit_id = ADC_UNIT };
    adc_oneshot_new_unit(&init_config, &adc_handle);

    adc_oneshot_chan_cfg_t chan_config = {
        .bitwidth = ADC_BITWIDTH_12,
        .atten = ADC_ATTEN_DB_12,
    };
    adc_oneshot_config_channel(adc_handle, ADC_CHANNEL, &chan_config);

    // Configuración del DAC (GPIO25)
    dac_oneshot_handle_t dac_handle;
    dac_oneshot_config_t dac_cfg = { .chan_id = DAC_CHANNEL };
    dac_oneshot_new_channel(&dac_cfg, &dac_handle);

    // Selección interactiva
    modo_ejercicio_t modo = seleccionar_ejercicio();

    uint64_t start_time = 0;
    int raw_adc = 0;
    unsigned long n = 0;

    uint8_t delay_buffer[DELAY];
    for (int i = 0; i < DELAY; i++) {
        delay_buffer[i] = 128; // Nivel de reposo DC (0.0 V de señal AC)
    }
    int delay_index = 0;

    while (1) {
        start_time = esp_timer_get_time();

        // PASO A: GENERACIÓN EN DAC (GPIO25)
        float val_signal = tabla_signal[n % TOTAL_MUESTRAS];
        uint8_t dac_gen_val = (uint8_t)((val_signal + 1.0f) * 127.5f);
        dac_oneshot_output_voltage(dac_handle, dac_gen_val);

        // PASO B: LECTURA EN ADC (GPIO34)
        adc_oneshot_read(adc_handle, ADC_CHANNEL, &raw_adc);
        
        // Convertimos la lectura de 12-bits (0-4095) a escala de 8-bits (0-255) para el Python
        uint8_t val_in = (uint8_t)(raw_adc >> 4); // División rápida por 16
        uint8_t val_out = 0;

        // PASO C: PROCESAMIENTO
        switch (modo) {
            case MODO_PASO_DIRECTO: // Ejercicio 1: Paso directo (y[n] = x[n])
                val_out = val_in;
                break;

            case MODO_GANANCIA:
            {
                float gain = GAIN; // Ajusta el valor de ganancia según requiera
            
                // Quitar offset: Convertir de [0, 255] a centrado en cero [-127.5, +127.5]
                float x_centered = (float)val_in - 127.5f;
                    
                // Aplicar Ganancia: y[n] = A * x[n]
                float y_centered = gain * x_centered;
                    
                // Restaurar offset: Volver al rango [0, 255]
                float y_dac = y_centered + 127.5f;
                    
                // Saturación / Anti-clipping (Garantizar rango 0 a 255)
                if (y_dac > 255.0f) y_dac = 255.0f;
                if (y_dac < 0.0f)   y_dac = 0.0f;
                    
                val_out = (uint8_t)y_dac;
                break;
            }
            case MODO_RETARDO:
            {
                // La salida es la muestra guardada hace DELAY ciclos atrás
                val_out = delay_buffer[delay_index];

                // Guardamos la muestra actual en el buffer
                delay_buffer[delay_index] = val_in;

                // Avanzamos el índice de forma circular
                delay_index = (delay_index + 1) % DELAY;
                break;
            }
            case MODO_DESPLAZAMIENTO:
            {
                // Valor de desplazamiento LEVEL
                float level = LEVEL; 

                // Sumar el desplazamiento escalado al rango de 8 bits
                float y_dac = (float)val_in + (level * 127.5f);

                // Control de saturación (Anti-clipping) en el rango [0, 255]
                if (y_dac > 255.0f) y_dac = 255.0f;
                if (y_dac < 0.0f)   y_dac = 0.0f;

                val_out = (uint8_t)y_dac;
                break;
            }
            case MODO_SENAL_SINUSOIDAL:
            {
                static float fase = 0.0f;

                // Genera la muestra (-1.0 a 1.0)
                float senoidal = sinf(fase);

                // Ajusta a la salida de 8 bits del DAC (0 a 255)
                val_out = (uint8_t)((senoidal + 1.0f) * 127.5f);

                // Avanza la fase a 200 Hz
                fase += 0.15707963f; 
                if (fase >= 6.2831853f) {
                    fase -= 6.2831853f;
                }
                break;
            }
            case MODO_SENAL_ALEATORIA:
            {
                val_out = (uint8_t)(rand() % 256);
                break;
            }
        }

        // SALIDA DE VOZ/DAC SECUNDARIO O MONITOR
        dac_oneshot_output_voltage(dac_handle, val_out);

        // FORMATO REQUERIDO POR  SCRIPT DE PYTHON EN PYQTGRAPH
        printf("Entrada:%d,Salida:%d\n", val_in, val_out);

        n++;

        // CONTROL TEMPORAL ESTRICTO (125 us)
        while ((esp_timer_get_time() - start_time) < SAMPLE_PERIOD_US);
    }
}